export type Faction = 'VILLAGER' | 'WEREWOLF' | 'THIRD_PARTY';

export type SeerResult = 'VILLAGER' | 'WEREWOLF';

export type WakeFrequency =
  | 'NEVER'
  | 'FIRST_NIGHT_ONLY'
  | 'EVERY_NIGHT'
  | 'EVERY_OTHER_NIGHT'
  | 'CONDITIONAL'
  | 'ON_DEATH';

export type RolePack = 'BASIC' | 'DEDUCTION' | 'CHAOS';

export type RoleTier = 'core' | 'advanced';

export interface RoleDefinition {
  id: string;
  nameVi: string;
  nameEn: string;
  pack: RolePack;
  faction: Faction;
  seerResult: SeerResult;
  balanceWeight: number;
  wakeFrequency: WakeFrequency;
  wakePriority: number | null;
  audioKey: string | null;
  shortDesc: string;
  edgeCases: string[];
  implementedInEngine: boolean;
  tier: RoleTier;
  playableInUI: boolean;
  multiDeviceOnly?: boolean;
}

export const CORE_ROLE_IDS = [
  'villager',
  'werewolf',
  'seer',
  'bodyguard',
  'witch',
  'hunter',
  'cupid',
  'wolf_cub',
] as const;

export type CoreRoleId = (typeof CORE_ROLE_IDS)[number];

export function isCoreRole(roleId: string): roleId is CoreRoleId {
  return (CORE_ROLE_IDS as readonly string[]).includes(roleId);
}

